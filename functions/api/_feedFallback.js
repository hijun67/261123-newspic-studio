export function curatedFor(category) {
  if (category === "all") {
    const ids = ["economy", "tech", "society", "entertain", "sports"];
    const out = [];
    for (let i = 0; i < 6; i += 1) {
      for (const id of ids) {
        const pool = CURATED_FEED[id];
        if (pool && pool[i]) out.push(pool[i]);
      }
    }
    return out.slice(0, 20);
  }
  return CURATED_FEED[category] || [];
}
